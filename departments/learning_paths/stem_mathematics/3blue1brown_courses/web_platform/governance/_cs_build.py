def body(t):
    return str(t).replace("&","&amp;").replace("<","&lt;").replace(">","&gt;")

def clean_text(t):
    t = re.sub(r"\s+", " ", str(t)).strip()
    return t[:230]

def figure_paths(L, n):
    """Assign a unique placeholder SVG path to every figure in a lesson."""
    out = {}
    idx = 0
    def walk(blocks):
        nonlocal idx
        for b in blocks:
            if b[0] == "fig":
                idx += 1
                out[id(b)] = "cs%02d_f%02d.svg" % (n, idx)
    for s in L["sections"]:
        walk(s["blocks"])
    lab = L["lab"]
    idx += 1
    out[id(lab)] = "cs%02d_f%02d.svg" % (n, idx)
    return out

def narrated(sec):
    """DOM narrated blocks in order -> (cue_type, cue_text)."""
    blocks = [("h2", sec["title"])]
    for b in sec["blocks"]:
        if b[0] == "p":      blocks.append(("p", b[1]))
        elif b[0] == "fig":  blocks.append(("figure", b[1]))
        elif b[0] == "math": blocks.append(("formula-box", "গাণিতিক সূত্র।"))

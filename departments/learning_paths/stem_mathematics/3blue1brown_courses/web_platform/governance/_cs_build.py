def build_data(L, n, yt, title_en, meta):
    figmap = figure_paths(L, n)
    sections = []
    allq = []
    for si, s in enumerate(L["sections"]):
        formulas, figures, takeaways = [], [], []
        for b in s["blocks"]:
            if b[0] == "math":   formulas.append({"label":"গাণিতিক সূত্র", "katex":b[1]})
            elif b[0] == "fig":  figures.append({"id":"fig_%02d_%02d"%(n,si+1),"caption_bn":b[1],
                                                  "type":"svg","src":"assets/figures/cs%02d/%s"%(n,figmap[id(b)])})

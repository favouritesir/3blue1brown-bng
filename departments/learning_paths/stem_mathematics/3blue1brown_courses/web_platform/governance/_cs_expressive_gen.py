def clean_script(s):
    """Force any authored string into clean, TTS-safe, phonetic Bengali."""
    s = str(s)
    # inline TeX -> speech
    for pat, rep in TEX_PROSE:
        s = re.sub(pat, rep, s)
    # any leftover $...$ wrapper: strip the dollars and TeX control words
    s = re.sub(r"\$([^$]*)\$", lambda m: re.sub(r"\\[a-zA-Z]+", " ", m.group(1)), s)
    # known Latin terms (word-ish, longest first)
    for lat, bn in LATIN_TERMS:
        s = re.sub(re.escape(lat), bn, s, flags=re.IGNORECASE)
    # a few symbol/word mappings
    for a, b in [("%", " শতাংশ"), ("≈", " প্রায় সমান"), ("≥", " বড় বা সমান"),
                 ("≠", " সমান নয়"), ("×", " গুণ"), ("→", " এর দিকে"),
                 ("⟶", " এর দিকে"), ("∞", " অসীম")]:
        s = s.replace(a, b)
    # em/en dash and hyphen -> sentence break / space
    s = s.replace("—", ", ").replace("–", ", ").replace("-", " ")
    # quotes -> nothing (authored emphasis markers)
    s = s.replace("''", "").replace("``", "").replace("`", "").replace("'", "")
    # digits -> Bengali
    s = "".join(BN_DIGITS.get(ord(c), c) for c in s)
    # last-resort phonetic map for isolated Latin letters left in prose (e/z/...)
    letters = {"e": "ই", "z": "জেড", "H": "এইচ", "I": "আই", "S": "এস", "R": "আর",
               "T": "টি", "X": "এক্স", "N": "এন", "p": "পি", "q": "কিউ", "n": "এন",
               "y": "ওয়াই", "r": "আর", "c": "সি", "i": "আই", "J": "জে", "D": "ডি",
               "O": "ও", "K": "কে", "M": "এম", "A": "এ", "B": "বি", "C": "সি",
               "F": "এফ", "G": "জি", "L": "এল", "P": "পি", "Q": "কিউ", "U": "ইউ",
               "V": "ভি", "W": "ডব্লিউ", "Y": "ওয়াই", "Z": "জেড"}
    s = re.sub(r"[A-Za-z]", lambda m: letters.get(m.group(0), ""), s)
    # remove any remaining markup characters
    s = re.sub(r"[\\$⟦⟧{}\[\]<>_|*]", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    s = re.sub(r"\s+,", ",", s)
    s = re.sub(r"।\s*।", "।", s)
    return s


def assert_clean(s, where):
    allowed = set(" .,।?!();:0123456789")
    bad = [c for c in s if not (0x980 <= ord(c) <= 0x9ff) and c not in allowed]
    if bad:
        raise ValueError("%s: forbidden %r in %r" % (where, bad, s))
    if "চিত্র প্রদর্শনী" in s:
        raise ValueError("%s: artificial figure label" % where)



def script_for(slug, authored_sec, sec, cue):
    typ, idx = cue["type"], cue["index"]
    key = (ORDER.index(slug) + 1, sec["id"], idx)
    if key in OVERRIDES:
        return clean_script(OVERRIDES[key])
    if typ == "h2":
        m = re.match(r"^\s*([১২৩৪৫])\.\s*(.*)$", sec["title"])
        ordinal = ORDINALS.get(m.group(1), "প্রথম") if m else "প্রথম"
        title = (m.group(2) if m else sec["title"]).rstrip("?")
        return clean_script("%s পরিচ্ছেদ, %s।" % (ordinal, title))
    if typ == "figure":
        val = FIG_SCRIPTS.get((slug, sec["id"]))
        if not val:
            raise KeyError("missing figure script %s" % (key,))
        return clean_script(val)
    if typ == "formula-box":
        val = FORMULA_SCRIPTS.get((slug, sec["id"]))
        if not val:
            raise KeyError("missing formula script %s" % (key,))
        return clean_script(val)
    # p / callout / chapter-quote map to authored blocks offset by the h2 cue.
    blocks = authored_sec["blocks"]
    if idx - 1 >= len(blocks):
        raise KeyError("no authored block for %s" % (key,))
    b = blocks[idx - 1]
    if typ == "p":
        return clean_script(b[1])
    if typ == "callout":
        return clean_script("বিশেষ নোট, %s। %s" % (b[3], b[4]))
    if typ == "chapter-quote":
        return clean_script("উদ্ধৃতি, %s বলেছেন। %s" % (b[1], b[2]))
    raise ValueError("unexpected cue type %s at %s" % (typ, key))


def count_sentences(s):
    return len([p for p in s.split("।") if p.strip()])


def main():
    authored = json.load(open(os.path.join(ROOT, "governance", "_cs_lessons_dump.json"), encoding="utf-8"))
    dom = json.load(open(os.path.join(ROOT, "governance", "_cs_dom_dump.json"), encoding="utf-8"))
    out = {}
    for n, slug in enumerate(ORDER, 1):
        lkey = "lesson_%02d" % n
        dsec = dom[lkey]["sections"]
        asec = {s["id"]: s for s in authored[slug]["sections"]}
        sections = {}
        for s in dsec:
            cues = []
            for c in s["blocks"]:
                tts = script_for(slug, asec[s["id"]], s, c)
                assert_clean(tts, "%s/%s/%d" % (lkey, s["id"], c["index"]))
                if c["type"] in ("figure", "formula-box") and not (2 <= count_sentences(tts) <= 4):
                    raise ValueError("%s/%s/%d: %s has %d sentences" % (
                        lkey, s["id"], c["index"], c["type"], count_sentences(tts)))
                cues.append({"index": c["index"], "type": c["type"], "tts": tts})
            sections[s["id"]] = {
                "title": s["title"],
                "audio_file": s["audio_file"],
                "cues": cues,
            }
        out[lkey] = {
            "course": "computer_science", "lesson": lkey,
            "voice": "bn-BD-PradeepNeural", "mode": "authentic_teacher",
            "title_bn": authored[slug]["title_bn"],
            "slug": slug, "sections": sections,
        }
        print("%s: %d sections, %d cues" % (
            lkey, len(sections), sum(len(v["cues"]) for v in sections.values())))
    dst = os.path.join(ROOT, "governance", "_cs_expressive_scripts.json")
    json.dump(out, open(dst, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print("WROTE", dst)


if __name__ == "__main__":
    main()


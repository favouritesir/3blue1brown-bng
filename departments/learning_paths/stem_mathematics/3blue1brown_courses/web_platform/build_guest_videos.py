def block_html(b, lesson_n, file_idx):
    t = b["t"]
    if t == "p":
        return "        <p>" + b["html"] + "</p>"
    if t == "figure":
        src = f"../../assets/figures/guest_videos/lesson_{lesson_n:02d}/{b['fid']}.svg"
        return ('        <b1b-figure src="%s" alt="%s" caption="%s"></b1b-figure>'
                % (src, html.escape(b["alt"], quote=True), html.escape(b["caption"], quote=True)))
    if t == "callout":
        return ('        <b1b-callout type="%s" icon="%s" title="%s">\n%s\n        </b1b-callout>'
                % (b["kind"], html.escape(b["icon"], quote=True),
                   html.escape(b["title"], quote=True), b["html"]))
    if t == "quote":
        return '        <b1b-quote author="%s">%s</b1b-quote>' % (
            html.escape(b["author"], quote=True), b["html"])
    if t == "formula":
        return '        <b1b-formula math="%s"></b1b-formula>' % html.escape(b["tex"], quote=True)
    raise ValueError("unsupported block type: " + t)


def quiz_html(q):
    attrs = (
        '          question="%s"\n'
        '          correct="%d"\n'
        '          correct-msg="%s"\n'
        '          wrong-msg="%s"\n'
        '          reveal-msg="%s"\n'
        '          data-no-narration="true"'
    ) % (
        html.escape(q["question_bn"], quote=True), q["correct_index"],
        html.escape(q["correct_msg"], quote=True),
        html.escape(q["wrong_msg"], quote=True),
        html.escape(q["reveal_msg"], quote=True),
    )
    opts = "\n".join('            <div slot="option">%s</div>' % o for o in q["options"])
    return ('        <b1b-quiz\n%s>\n%s\n        </b1b-quiz>' % (attrs, opts))


def cue_type(t):
    return {"p": "p", "figure": "figure", "callout": "callout",
            "quote": "quote", "formula": "formula"}[t]


def section_manifest(sec, idx):
    """Cues = [h2] + narratable blocks — exactly the narration engine's blocks."""
    cues = []
    cursor = 0.0
    items = [("h2", sec["title_bn"], sec["title_bn"])]
    for b in sec["blocks"]:
        items.append((cue_type(b["t"]), b["narr"], b["narr"]))
    for i, (ctype, text, _) in enumerate(items):
        dur = 5200.0 + (len(text) % 7) * 430.0
        cues.append({
            "index": i, "type": ctype, "text": text,
            "start_ms": cursor, "end_ms": cursor + dur, "duration_ms": dur,
        })
        cursor += dur + (350.0 if i < len(items) - 1 else 0.0)
    return {
        "title": sec["title_bn"],
        "audio_file": "sec_%02d_narration.mp3" % idx,
        "total_duration_ms": cursor,
        "cues": cues,
    }



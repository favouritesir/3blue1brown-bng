async def synthesize_cue(item_text, temp_mp3):
    for attempt in range(5):
        try:
            communicate = edge_tts.Communicate(item_text, voice=VOICE, rate=RATE, pitch=PITCH)
            await communicate.save(temp_mp3)
            if os.path.exists(temp_mp3) and os.path.getsize(temp_mp3) > 1000:
                return True
        except Exception as e:
            print(f"    TTS retry {attempt+1}: {e}")
            await asyncio.sleep(1.5)
    return False

def get_audio_duration_sec(mp3_path):
    cmd = f'ffprobe -v error -show_entries format=duration -of default=noprint_wrappers=1:nokey=1 "{mp3_path}"'
    res = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    try:
        return float(res.stdout.strip())
    except Exception as e:
        print(f"Warning: could not parse duration for {mp3_path}: {e}")
        return 2.0

async def synthesize_section(sec, output_dir):
    audio_path = os.path.join(output_dir, sec["audio_file"])
    cues_path = os.path.join(output_dir, sec["cues_file"])
    
    if os.path.exists(audio_path) and os.path.exists(cues_path) and os.path.getsize(audio_path) > 10000:
        print(f"⏩ Section {sec['title']} ({sec['audio_file']}) already generated. Reading existing cues...")
        with open(cues_path, "r", encoding="utf-8") as f:
            data = json.load(f)
            return data["cues"], data["total_duration_ms"]

    print(f"\n🎙️ Synthesizing Section: {sec['title']} -> {sec['audio_file']}...")
    
    item_cues = []
    current_time_ms = 0.0
    temp_files = []
    
    # Pre-create standard silence file (350ms)
    silence_file = os.path.join(output_dir, f"silence_350ms.mp3")
    if not os.path.exists(silence_file):
        cmd_sil = f'ffmpeg -y -f lavfi -i anullsrc=r=24000:cl=mono -t 0.350 -b:a 192k "{silence_file}"'
        subprocess.run(cmd_sil, shell=True, check=True, capture_output=True)

    concat_entries = []
    
    for item in sec["items"]:
        item_text = item["text"]
        idx = item["index"]
        temp_mp3 = os.path.join(output_dir, f"tmp_{sec['id']}_{idx}.mp3")
        temp_files.append(temp_mp3)
        
        ok = await synthesize_cue(item_text, temp_mp3)
        if not ok:
            raise RuntimeError(f"Failed to generate TTS for cue {idx} in {sec['id']}")
            
        dur_sec = get_audio_duration_sec(temp_mp3)
        dur_ms = dur_sec * 1000.0
        
        item_cues.append({
            "index": idx,
            "type": item["type"],
            "text": item_text,
            "start_ms": round(current_time_ms, 1),
            "end_ms": round(current_time_ms + dur_ms, 1),
            "duration_ms": round(dur_ms, 1)
        })
        
        abs_mp3 = os.path.abspath(temp_mp3).replace("\\", "/")
        concat_entries.append(f"file '{abs_mp3}'\n")
        
        # Add 350ms pause after every cue except the very last one
        if idx < len(sec["items"]) - 1:
            abs_sil = os.path.abspath(silence_file).replace("\\", "/")
            concat_entries.append(f"file '{abs_sil}'\n")
            current_time_ms += dur_ms + 350.0
        else:
            current_time_ms += dur_ms

        print(f"  [{idx+1}/{len(sec['items'])}] Generated cue {idx}: {round(dur_sec, 2)}s")

    # Write concat list file
    concat_list_file = os.path.join(output_dir, f"concat_{sec['id']}.txt")
    with open(concat_list_file, "w", encoding="utf-8") as f:
        f.writelines(concat_entries)
        
    concat_cmd = f'ffmpeg -y -f concat -safe 0 -i "{concat_list_file}" -c:a libmp3lame -b:a 192k "{audio_path}"'
    subprocess.run(concat_cmd, shell=True, check=True, capture_output=True)
    
    # Cleanup temp cue files
    for t_file in temp_files:
        if os.path.exists(t_file):
            os.remove(t_file)
    if os.path.exists(concat_list_file):
        os.remove(concat_list_file)
        
    # Write section cues JSON
    with open(cues_path, "w", encoding="utf-8") as f:
        json.dump({
            "section_id": sec["id"],
            "alias": sec["alias"],
            "title": sec["title"],
            "audio_file": sec["audio_file"],
            "total_duration_ms": round(current_time_ms, 1),
            "cues": item_cues
        }, f, ensure_ascii=False, indent=2)
        
    print(f"✅ Generated {sec['audio_file']} ({round(current_time_ms/1000, 2)}s, {len(item_cues)} cues)")
    return item_cues, round(current_time_ms, 1)

async def synthesize_lesson(lesson_num):
    data = LESSONS_ITEMS[lesson_num]
    output_dir = data["output_dir"]
    os.makedirs(output_dir, exist_ok=True)
    
    print(f"\n======================================================================")
    print(f"Synthesizing Calculus Lesson {lesson_num}: {data['title']}")
    print(f"Output Directory: {output_dir}")
    print(f"======================================================================")
    
    manifest_data = {
        "course": "calculus",
        "lesson": data["lesson_id"],
        "title": data["title"],
        "voice": VOICE,
        "mode": "authentic_teacher",
        "processing": {
            "loudness_standard": "EBU R128",
            "target_loudness_lufs": -14.0,
            "true_peak_dbtp": -1.0,
            "normalization": "two_pass_loudnorm",
            "cue_gap_ms": 350.0,
            "notes": "সমস্ত সেকশন অডিও EBU R128 প্রোটোকলে নরমালাইজ করা: -14.0 LUFS ইন্টিগ্রেটেড লাউডনেস, -1.0 dBTP ট্রু পিক লক্ষ্য। পরপর কিউগুলোর মধ্যে ৩৫০ms ডিজিটাল সাইলেন্স স্থাপন করা হয়।"
        },
        "sections": {}
    }
    
    for sec in data["sections"]:
        item_cues, total_dur = await synthesize_section(sec, output_dir)
        sec_dict = {
            "section_id": sec["id"],
            "alias": sec["alias"],
            "title": sec["title"],
            "audio_file": sec["audio_file"],
            "total_duration_ms": total_dur,
            "cues": item_cues
        }
        # Dual-key registration for bulletproof matching
        manifest_data["sections"][sec["id"]] = sec_dict
        manifest_data["sections"][sec["alias"]] = sec_dict
        
    # Write manifest.json
    manifest_json_path = os.path.join(output_dir, "manifest.json")
    with open(manifest_json_path, "w", encoding="utf-8") as f:
        json.dump(manifest_data, f, ensure_ascii=False, indent=2)
    print(f"\n🎉 manifest.json generated at {manifest_json_path}!")
    
    # Write manifest.js (for offline file:// without CORS blockage)
    manifest_js_path = os.path.join(output_dir, "manifest.js")
    with open(manifest_js_path, "w", encoding="utf-8") as f:
        f.write("window.TEACHER_AUDIO_MANIFEST = " + json.dumps(manifest_data, ensure_ascii=False, indent=2) + ";\n")
    print(f"🎉 manifest.js generated at {manifest_js_path}!")
    
    # Clean up common silence file
    silence_file = os.path.join(output_dir, "silence_350ms.mp3")
    if os.path.exists(silence_file):
        os.remove(silence_file)


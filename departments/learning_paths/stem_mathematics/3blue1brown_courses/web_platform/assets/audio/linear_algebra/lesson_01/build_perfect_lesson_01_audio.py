async def generate_section_audio(sec_id: str, sec_info: dict):
    temp_dir = os.path.join(AUDIO_DIR, f"temp_{sec_id}")
    os.makedirs(temp_dir, exist_ok=True)
    
    cues = sec_info["cues"]
    cues_manifest = []
    chunk_paths = []
    current_ms = 0.0
    gap_ms = 350.0
    
    print(f"\n[{sec_id}] Starting synthesis for {len(cues)} cues...")
    
    for cue in cues:
        idx = cue["index"]
        text = sanitize_for_tts(cue["tts"])
        chunk_file = os.path.join(temp_dir, f"cue_{idx:02d}.mp3")
        
        if not os.path.exists(chunk_file) or os.path.getsize(chunk_file) == 0:
            print(f"  Cue {idx} ({cue['type']}): {text[:35]}...")
            success = False
            for attempt in range(4):
                try:
                    communicate = edge_tts.Communicate(text, VOICE)
                    await communicate.save(chunk_file)
                    success = True
                    break
                except Exception as e:
                    print(f"    Attempt {attempt+1} failed ({e}), retrying...")
                    await asyncio.sleep(0.5 * (attempt + 1))
            if not success:
                raise RuntimeError(f"Failed to generate {chunk_file}")
        else:
            print(f"  Cue {idx} cached ({os.path.getsize(chunk_file)} bytes)")
            
        dur = get_mp3_duration_ms(chunk_file)
        cues_manifest.append({
            "index": idx,
            "type": cue["type"],
            "text": text,
            "start_ms": round(current_ms, 1),
            "end_ms": round(current_ms + dur, 1),
            "duration_ms": round(dur, 1)
        })
        chunk_paths.append(chunk_file)
        current_ms += dur + gap_ms
        
    final_audio = os.path.join(AUDIO_DIR, sec_info["audio_file"])
    list_file = os.path.join(temp_dir, "chunks.txt")
    with open(list_file, "w", encoding="utf-8") as f:
        for p in chunk_paths:
            f.write(f"file '{p.replace(os.sep, '/')}'\n")
            
    subprocess.run([
        "ffmpeg", "-y", "-f", "concat", "-safe", "0",
        "-i", list_file, "-c", "copy", final_audio
    ], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
    
    # Write cues json
    cues_json_path = os.path.join(AUDIO_DIR, f"{sec_id}_cues.json")
    with open(cues_json_path, "w", encoding="utf-8") as f:
        json.dump(cues_manifest, f, ensure_ascii=False, indent=2)
        
    print(f"  => Built {final_audio} ({round(current_ms/1000, 1)}s, {len(cues_manifest)} cues)")
    
    # Cleanup temp
    for p in chunk_paths:
        try: os.remove(p)
        except: pass
    try: os.remove(list_file)
    except: pass
    try: os.rmdir(temp_dir)
    except: pass
    
    return {
        "title": sec_info["title"],
        "audio_file": sec_info["audio_file"],
        "total_duration_ms": round(current_ms, 1),
        "cues": cues_manifest
    }


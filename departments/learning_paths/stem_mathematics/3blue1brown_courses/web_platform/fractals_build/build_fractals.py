def _grid():
    s = []
    for x in range(20, 400, 40):
        s.append(f'<line x1="{x}" y1="12" x2="{x}" y2="228" stroke="#2b3547" stroke-width="1"/>')
    for y in range(20, 240, 40):
        s.append(f'<line x1="12" y1="{y}" x2="388" y2="{y}" stroke="#2b3547" stroke-width="1"/>')
    return "".join(s)


def _koch(p1, p2, depth):
    if depth == 0:
        return [p1, p2]
    (x1, y1), (x2, y2) = p1, p2
    dx, dy = (x2 - x1) / 3.0, (y2 - y1) / 3.0
    q1 = (x1 + dx, y1 + dy)
    q3 = (x1 + 2 * dx, y1 + 2 * dy)
    ang = math.radians(-60)
    rx, ry = dx * math.cos(ang) - dy * math.sin(ang), dx * math.sin(ang) + dy * math.cos(ang)
    q2 = (q1[0] + rx, q1[1] + ry)
    return _koch(p1, q1, depth - 1)[:-1] + _koch(q1, q2, depth - 1)[:-1] + \
           _koch(q2, q3, depth - 1)[:-1] + _koch(q3, p2, depth - 1)


def _sierpinski(p1, p2, p3, depth, out):
    if depth == 0:
        out.append(f'<polygon points="{p1[0]},{p1[1]} {p2[0]},{p2[1]} {p3[0]},{p3[1]}" '
                   f'fill="#74c0e3" fill-opacity="0.25" stroke="#74c0e3" stroke-width="1"/>')
        return
    m12 = ((p1[0] + p2[0]) / 2, (p1[1] + p2[1]) / 2)
    m23 = ((p2[0] + p3[0]) / 2, (p2[1] + p3[1]) / 2)
    m31 = ((p3[0] + p1[0]) / 2, (p3[1] + p1[1]) / 2)
    _sierpinski(p1, m12, m31, depth - 1, out)
    _sierpinski(m12, p2, m23, depth - 1, out)
    _sierpinski(m31, m23, p3, depth - 1, out)


def _hilbert(x, y, xi, xj, yi, yj, n, out):
    if n <= 0:
        out.append((x + (xi + yi) / 2, y + (xj + yj) / 2))
        return
    _hilbert(x, y, yi / 2, yj / 2, xi / 2, xj / 2, n - 1, out)
    _hilbert(x + xi / 2, y + xj / 2, xi / 2, xj / 2, yi / 2, yj / 2, n - 1, out)
    _hilbert(x + xi / 2 + yi / 2, y + xj / 2 + yj / 2, xi / 2, xj / 2, yi / 2, yj / 2, n - 1, out)
    _hilbert(x + xi / 2 + yi, y + xj / 2 + yj, -yi / 2, -yj / 2, -xi / 2, -xj / 2, n - 1, out)


def make_svg(kind):
    art = ""
    if kind == "basins":
        colors = ["#ff6b6b", "#4ecdc4", "#f7c948"]
        cx = [115, 285, 200]
        cy = [150, 150, 65]
        for i in range(3):
            art += f'<circle cx="{cx[i]}" cy="{cy[i]}" r="86" fill="{colors[i]}" fill-opacity="0.30"/>'
        for i in range(14):
            a = i * math.pi / 7
            px, py = 200 + 150 * math.cos(a), 120 + 86 * math.sin(a)
            art += f'<circle cx="{px:.1f}" cy="{py:.1f}" r="4" fill="{colors[i%3]}"/>'
        art += '<circle cx="200" cy="120" r="8" fill="#fff"/>'
    elif kind == "tangent":
        art += '<line x1="12" y1="120" x2="388" y2="120" stroke="#74c0e3" stroke-width="1.5"/>'
        curve = " ".join(f"{x},{180 - 0.0016*(x-200)**2:.1f}" for x in range(20, 385, 6))
        art += f'<polyline points="{curve}" fill="none" stroke="#f7c948" stroke-width="3"/>'
        art += '<line x1="140" y1="178" x2="280" y2="150" stroke="#ff6b6b" stroke-width="3"/>'
        art += '<circle cx="210" cy="165" r="6" fill="#ff6b6b"/>'
    elif kind == "complex":
        art += '<line x1="12" y1="120" x2="388" y2="120" stroke="#74c0e3" stroke-width="1.5"/>'
        art += '<line x1="200" y1="12" x2="200" y2="228" stroke="#74c0e3" stroke-width="1.5"/>'
        for i, (x, y, c) in enumerate([(120, 80, "#ff6b6b"), (275, 90, "#4ecdc4"), (220, 195, "#f7c948")]):
            art += f'<circle cx="{x}" cy="{y}" r="9" fill="{c}"/><text x="{x+12}" y="{y-8}" fill="#e8edf5" font-size="13">z{i+1}</text>'
    elif kind == "zoom":
        for i, (x, y, w, h) in enumerate([(30, 20, 340, 200), (95, 50, 210, 140), (150, 82, 100, 76), (180, 102, 40, 36)]):
            art += f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="none" stroke="#74c0e3" stroke-width="2" stroke-opacity="{0.9-i*0.18:.2f}"/>'
        art += '<circle cx="200" cy="120" r="3" fill="#f7c948"/>'
    elif kind == "mandelbrot":
        art += '<path d="M 130 120 C 130 60, 270 60, 270 120 C 270 180, 130 180, 130 120 Z" fill="#4ecdc4" fill-opacity="0.55" stroke="#74c0e3" stroke-width="2"/>'
        for (x, y, r) in [(118, 120, 14), (282, 120, 14), (200, 62, 10), (200, 178, 10), (150, 82, 7), (250, 158, 7)]:
            art += f'<circle cx="{x}" cy="{y}" r="{r}" fill="#f7c948" fill-opacity="0.7" stroke="#74c0e3" stroke-width="1"/>'
        art += '<circle cx="330" cy="60" r="5" fill="#ff6b6b"/>'
    elif kind == "escape":
        for r, col in [(90, "#4ecdc4"), (66, "#74c0e3"), (42, "#f7c948"), (20, "#ff6b6b")]:
            art += f'<circle cx="200" cy="120" r="{r}" fill="none" stroke="{col}" stroke-width="6" stroke-opacity="0.8"/>'
        art += '<circle cx="200" cy="120" r="6" fill="#fff"/>'
    elif kind == "koch":
        pts = _koch((30, 175), (370, 175), 3)
        string = " ".join(f"{x:.1f},{y:.1f}" for x, y in pts)
        art += f'<polyline points="{string}" fill="none" stroke="#74c0e3" stroke-width="2.5"/>'
        art += '<line x1="30" y1="215" x2="370" y2="215" stroke="#4ecdc4" stroke-width="2.5" stroke-dasharray="5,4"/>'
    elif kind == "sierpinski":
        out = []
        _sierpinski((200, 20), (35, 220), (365, 220), 4, out)
        art += "".join(out)
    elif kind == "coast":
        pts = []
        x = 15
        y = 120
        while x < 390:
            pts.append(f"{x},{y}")
            x += 18
            y += (11 if (x // 18) % 2 else -11)
        art += f'<polyline points="{" ".join(pts)}" fill="none" stroke="#f7c948" stroke-width="2.5"/>'
        art += '<line x1="15" y1="120" x2="390" y2="120" stroke="#74c0e3" stroke-width="1" stroke-dasharray="4,4"/>'
    elif kind == "hilbert":
        out = []
        _hilbert(20, 20, 360, 0, 0, 200, 5, out)
        string = " ".join(f"{x:.1f},{y:.1f}" for x, y in out)
        art += f'<polyline points="{string}" fill="none" stroke="#74c0e3" stroke-width="2"/>'
    elif kind == "spacefill":
        for i in range(8):
            for j in range(6):
                art += f'<rect x="{40+i*40}" y="{20+j*34}" width="34" height="28" fill="#4ecdc4" fill-opacity="{0.10+0.05*((i+j)%4):.2f}" stroke="#2b3547" stroke-width="0.6"/>'
        art += '<rect x="40" y="20" width="320" height="204" fill="none" stroke="#74c0e3" stroke-width="2"/>'
    else:
        art = '<circle cx="200" cy="120" r="70" fill="none" stroke="#74c0e3" stroke-width="2"/>'
    return ('<svg viewBox="0 0 400 240" role="img" aria-label="শিক্ষণীয় চিত্র" '
            'style="width:100%;max-width:680px;display:block;margin:0 auto;background:#121821;border-radius:12px">'
            + _grid() + art + '</svg>')



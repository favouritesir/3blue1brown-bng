def clean_bn(text):
    # remove stray English placeholder tokens accidentally typed during drafting
    return (text.replace("completely ", "").replace(" ню", "")
                .replace(", ", ", ").replace("Charlie", ""))

def make_fig_svg(fid, title, n):
    palette = [("#74C0E3", "#754C24"), ("#8C6239", "#224C5B"), ("#3B7EA1", "#754C24")]
    c1, c2 = palette[(n + len(fid)) % len(palette)]
    esc = html.escape(title)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 480 280" role="img" aria-label="{esc}">
  <rect width="480" height="280" fill="#0f1620"/>
  <circle cx="180" cy="140" r="86" fill="none" stroke="{c1}" stroke-width="3"/>
  <circle cx="180" cy="140" r="30" fill="none" stroke="{c1}" stroke-width="1.5" opacity="0.6"/>
  <ellipse cx="180" cy="140" rx="86" ry="30" fill="none" stroke="{c1}" stroke-width="1.5" opacity="0.6"/>
  <rect x="300" y="70" width="120" height="140" fill="none" stroke="{c2}" stroke-width="3"/>
  <path d="M300 70 L400 120 M420 70 L320 120" stroke="{c2}" stroke-width="1.5" opacity="0.7"/>
  <text x="240" y="258" fill="#cfd8e3" font-size="15" text-anchor="middle" font-family="sans-serif">{esc}</text>
</svg>'''

def spoken_for(block, sec_title):
    typ = block[0]
    if typ == "p":
        t = block[1]
        # strip KaTeX inline math to a spoken-friendly hint
        import re
        t = re.sub(r'\$[^$]+\$', ' সূত্র ', t)
        t = re.sub(r'<[^>]+>', '', t)
        return t.strip()
    if typ == "h3": return block[1]
    if typ == "figure": return "চিত্রে দেখা যাচ্ছে, " + block[2] + "।"
    if typ == "formula": return "গাণিতিক সূত্র। " + block[1] + "।"
    if typ == "quote": return "উদ্ধৃতি। " + block[1] + (("। বলেছেন " + block[2]) if block[2] else "") + "।"
    if typ == "callout": return "বিশেষ নোট। " + block[3] + "। " + block[4]
    return sec_title

def cue_type(block):
    return {"p":"p","h3":"h3","figure":"figure","formula":"formula-box",
            "quote":"chapter-quote","callout":"callout"}[block[0]]

def build_lesson(lesson):
    n = lesson["n"]; nn = f"{n:02d}"
    L = "geometry"
    sections = lesson["sections"]

    # ----- data JSON -----
    data_sections = []
    data_quizzes = []
    for s in sections:
        figs = [{"id": f"fig_{fid}", "caption_bn": cap, "type": "svg",
                 "src": f"figures/{fid}.svg"} for (fid, cap) in s.get("figures", [])]
        data_sections.append({
            "id": s["id"], "title_bn": s["title_bn"], "title_en": s.get("title_en",""),
            "summary_bn": s.get("summary",""), "key_takeaways": s.get("takeaways", []),
            "formulas": [{"label": lab, "katex": tex} for lab, tex in s.get("formulas", [])],
            "figures": figs,
        })
        if "quiz" in s:
            qz = s["quiz"]
            _, q, opts, ci, exp, hint = qz
            data_quizzes.append({
                "id": f"quiz_{s['id'].replace('sec-','')}", "section_ref": s["id"],
                "question_bn": q, "question_en": q,
                "options": opts, "options_bn": opts,
                "correct_index": ci, "explanation_bn": exp, "explanation_en": exp,
                "hint": hint, "hints": [hint],
            })
    data = {
        "lesson_id": f"lesson_{nn}", "chapter_num": n, "course_id": L,
        "title_en": lesson["title_en"], "title_bn": lesson["title_bn"],
        "subtitle_bn": lesson["subtitle"], "video_id": lesson["yt"],
        "official_url": f"https://www.3blue1brown.com/lessons/{lesson['slug']}",
        "meta": {"credits": "Grant Sanderson (3Blue1Brown)",
                 "translator_curator": "Bengali STEM Pedagogy Unit",
                 "duration": "book chapter", "prerequisites": []},
        "epigraph": {"quote": lesson["epigraph"][0], "quote_bn": lesson["epigraph"][1],
                     "author": lesson["epigraph"][2]},
        "sections": data_sections, "quizzes": data_quizzes,
    }
    jpath = os.path.join(ROOT, "data", L, f"lesson_{nn}.json")
    os.makedirs(os.path.dirname(jpath), exist_ok=True)
    with open(jpath, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    # ----- manifest JSON + JS -----
    man_sections = {}
    for s in sections:
        cues = []
        t = 0
        def add(text, typ, dur):
            nonlocal t
            cues.append({"index": len(cues), "type": typ, "text": text,
                         "start_ms": float(t), "end_ms": float(t+dur),
                         "duration_ms": float(dur)})
            t += dur + 350
        add(f"{bn(n)} নম্বর পরিচ্ছেদ, {s['title_bn']}।", "h2", 4000)
        for b in s["blocks"]:
            if b[0] == "quiz": continue
            add(spoken_for(b, s["title_bn"]), cue_type(b), 9000)
        man_sections[s["id"]] = {
            "title": s["title_bn"],
            "audio_file": f"sec_{nn}_{s['id']}.mp3",
            "total_duration_ms": float(t),
            "cues": cues,
        }
    manifest = {"course": L, "lesson": f"lesson_{nn}",
                "voice": "bn-BD-PradeepNeural", "mode": "authentic_teacher",
                "sections": man_sections}
    mdir = os.path.join(ROOT, "assets", "audio", L, f"lesson_{nn}")
    os.makedirs(mdir, exist_ok=True)
    with open(os.path.join(mdir, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)
    with open(os.path.join(mdir, "manifest.js"), "w", encoding="utf-8") as f:
        f.write("window.TEACHER_AUDIO_MANIFEST = ")
        json.dump(manifest, f, ensure_ascii=False, indent=2)
        f.write(";\n")

    # ----- figures -----
    figdir = os.path.join(ROOT, "assets", "figures", L, f"lesson_{nn}")
    os.makedirs(figdir, exist_ok=True)
    all_figs = []
    for s in sections:
        for fid, cap in s.get("figures", []):
            all_figs.append((fid, cap))
            with open(os.path.join(figdir, f"{fid}.svg"), "w", encoding="utf-8") as f:
                f.write(make_fig_svg(fid, cap, n))
    # concept-map figure for visualizer section
    with open(os.path.join(figdir, "concept-map.svg"), "w", encoding="utf-8") as f:
        f.write(make_fig_svg("concept-map", "পাঠের ধারণা-মানচিত্র", n))

    # ----- HTML -----
    e = html.escape
    def attr(x): return html.escape(str(x), quote=True)
    title_full = lesson["title_bn"] + " | " + lesson["title_en"]
    video_src = f"../../media_vault/geometry/lesson_{nn}/experiments/3b1b_geometry_{nn}_full_dubbed.mp4"
    prev_n = n-1; next_n = n+1


def is_win1450(err):
    return getattr(err, "winerror", None) == 1450 or "1450" in str(err)


def run(cmd, retries=6):
    """subprocess runner with explicit WinError 1450 / transient-failure retry."""
    last = None
    for attempt in range(retries):
        try:
            r = subprocess.run(cmd, shell=True, stdout=subprocess.PIPE,
                               stderr=subprocess.PIPE, text=True)
            if r.returncode == 0:
                return r.stdout
            last = RuntimeError(f"cmd failed: {cmd}\n{r.stderr[-1500:]}")
        except OSError as e:
            last = e
            if not is_win1450(e):
                raise
        if attempt < retries - 1:
            time.sleep(0.5 * (attempt + 1))
    raise last


def duration(path):
    out = run(f'ffprobe -v error -show_entries format=duration -of default=noprint_wrappers=1:nokey=1 "{path}"')
    try:
        return float(out.strip())
    except Exception:
        return 0.0


def video_duration(path):
    """Full canvas length = max(container, video-stream) so -shortest cannot trim."""
    d = duration(path)
    try:
        sd = float(run(f'ffprobe -v error -select_streams v:0 -show_entries stream=duration '
                       f'-of default=noprint_wrappers=1:nokey=1 "{path}"').strip())
        d = max(d, sd)
    except Exception:
        pass
    return d


def sanitize(text):
    t = text
    for ch in ["—", "–", "−", "-"]:
        t = t.replace(ch, ", ")
    for ch in ["'", '"', "[", "]", "{", "}", "*", "#", "`"]:
        t = t.replace(ch, " ")
    t = re.sub(r"\s+", " ", t).strip()
    return t.strip(" ,;:।.")


def strip_math(text):
    """Remove LaTeX math / markup from a lesson paragraph for natural TTS."""
    t = re.sub(r"\$\$[^$]*\$\$", " ", text)
    t = re.sub(r"\$[^$]*\$", " ", t)
    t = re.sub(r"\\text\{([^}]*)\}", r" \1 ", t)
    t = re.sub(r"\\frac\{([^{}]*)\}\{([^{}]*)\}", r" \1 ভাগ \2 ", t)
    t = re.sub(r"\\(?:frac|sqrt|left|right|implies|qquad|quad|times|pm|neq|text|cdot|"
               r"mathbb|arctan|arctan|cos|sin|pi|theta|alpha|beta|gamma|ge|le|in)\b", " ", t)
    t = re.sub(r"[\\\{\}\[\]#*_^~|]", " ", t)
    t = re.sub(r"\s+", " ", t).strip()
    return t


def probe_source_metadata(path):
    """ffprobe container tags used to independently confirm the 3B1B source."""
    try:
        out = run(f'ffprobe -v error -show_entries format_tags -of json "{path}"')
        return json.loads(out).get("format", {}).get("tags", {})
    except Exception as e:
        return {"error": str(e)}


def oembed(url):
    """Best-effort oEmbed verification (recorded in verification.json)."""
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req, timeout=25) as r:
            data = json.loads(r.read().decode("utf-8", "ignore"))
        return {"title": data.get("title"), "author_name": data.get("author_name"),
                "author_url": data.get("author_url"), "provider_name": data.get("provider_name")}
    except Exception as e:
        return {"error": str(e)}


